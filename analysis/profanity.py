"""
profanity.py
API 응답을 만들 때(출력 단계에서만) LLM 답변과 출처 제목에 섞인 명백한 욕설을
[욕설]로 마스킹한다.

크롤링된 원문/Mongo에 저장된 데이터는 건드리지 않는다 — "밈이 곧 욕설인 경우"
(예: ㅈㄱㄴ)까지 설명이 불가능해지면 안 되므로, 데이터 자체를 자르거나
숨기지 않고 화면에 보여줄 때만 마스킹한다. 성별·가족 비하와 명백한 욕설을
포함하되, 일반 단어(미친, 새끼, 걸레, 한남동 등)를 무조건 지우지 않는다.
이는 알려진 표현에 대한 출력 필터이며 모든 비하 표현을 판별하는 분류기는 아니다.
"""

import re

# (패턴, 표시용 라벨) — 라벨은 로그/테스트에서 "무슨 어근이 걸렸는지" 알아보기 쉽게 붙인 것,
# 실제 치환 결과는 전부 동일하게 "[욕설]"이다.
_PROFANITY_ROOTS = [
    # 씨발류
    "씨발", "씨팔", "시발", "씨빨", "씨불", "씨바",
    # 좆류(신체 비하 어근 + 흔한 활용형). "좆"/"좇" 단독도 넣는다 — "미친"/"새끼"와
    # 달리 이 음절 자체가 일상 단어에 우연히 섞여 들어갈 일이 없다("민좆"처럼
    # 접두어가 붙어도 항상 비속어).
    "좆같", "좆까", "좆되", "좆망", "좆밥", "좇같", "좇까", "좆", "좇",
    # 개새끼류
    "개새끼", "개새키", "개색끼",
    # 씹+비속어 결합형
    "씹새끼", "씹치", "씹할",
    # 장애 비하어
    "병신", "븅신",
    # 가족 모욕
    "니미", "니애미", "느금마", "애미터진", "애미뒤진", "애비뒤진",
    # 성별 비하 및 욕설 활용형
    "남충", "여혐충", "여충", "한녀", "김치녀", "된장녀", "맘충", "이년", "저년", "이지랄",
    # 성적 비하
    "창녀", "매춘부",
]

_MASK = "[욕설]"
# 지명 '한남동/한남대/한남대로'는 유지하고, 단독 또는 비하 표현의 접두어만 순화한다.
_GENDER_SLUR = re.compile(r"한남(?=말투|충|들|남|녀|[\s~.,!?\"'()·]|$)")

# 긴 어근부터 매칭해야 "좆같"이 "좆같은"의 부분으로 먼저 걸리는 식으로
# 겹치는 후보 중 더 구체적인 쪽이 우선한다(현재 목록엔 겹침이 거의 없지만
# 목록이 늘어날 걸 감안해 안전하게 정렬).
_PATTERN = re.compile("|".join(re.escape(w) for w in sorted(_PROFANITY_ROOTS, key=len, reverse=True)))


def soften_profanity(text: str | None) -> str | None:
    """text에서 알려진 욕설 어근을 전부 [욕설]로 치환한다. None은 그대로 None."""
    if text is None:
        return None
    return _GENDER_SLUR.sub(_MASK, _PATTERN.sub(_MASK, text))
