"""
keyword_shape.py
검색어가 밈/신조어처럼 보이는지 최소한의 규칙으로 가늠한다.

이 서비스의 크롤러(tavily_crawler 등)는 전부 "짧은 신조어"를 전제로 쿼리를 짠다
(키워드 전체를 큰따옴표로 감싼 완전일치, "뜻 유래 밈 인터넷 커뮤니티" 수식어 등).
그래서 "언어 치료사 1급 합격 방법"처럼 단어 수가 많은 자연어 질문을 넣으면,
실제로는 웹에 관련 자료가 있어도 완전일치 쿼리가 그 문구 그대로를 요구해서
크롤링이 전부 0건으로 끝난다(크롤러/전처리/임베딩까지 10~20분을 다 쓰고 나서야
"수집된 데이터가 없습니다"로 실패). 요청 시점에 미리 걸러 그 이유를 바로 보여준다.
"""

MEME_MAX_WORDS = 3  # 이 값을 초과하는 단어 수(공백 기준)면 문장형 질문으로 본다


def classify_keyword_shape(keyword: str) -> tuple[bool, str | None]:
    """(밈/신조어로 보이면 True, 아니면 그 이유)를 반환한다.
    이유는 사용자에게 그대로 보여줄 수 있는 문장이다."""
    words = keyword.split()
    if len(words) > MEME_MAX_WORDS:
        return False, (
            f"'{keyword}'는 단어 {len(words)}개로 이루어진 문장형 질문에 가까워요. "
            "이 서비스는 밈·신조어처럼 짧은 단어를 대상으로 자료를 찾습니다."
        )
    return True, None
